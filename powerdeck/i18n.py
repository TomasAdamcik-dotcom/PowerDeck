def _lang() -> str:
    for v in ("LC_ALL", "LC_MESSAGES", "LANG"):
        if os.environ.get(v):
            return os.environ[v][:2]
    return "en"


def _(s: str) -> str:
    return SK.get(s, s) if _lang() == "sk" else s
